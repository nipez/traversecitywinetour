#!/usr/bin/env python3
"""Merge winter-hours research into data-*.json, emit js/venue-hours-data.js,
and re-sync HTML data-hours attributes / schema via patch_open_this_week."""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESEARCH = ROOT / "scripts/hours_research_2026_11_25.json"
sys.path.insert(0, str(ROOT / "scripts"))

HOURS_FIELDS = (
    "hours",
    "hoursStatus",
    "hoursCheckedAt",
    "hoursSource",
    "hoursNote",
    "hoursSchedules",
    "holidayClosures",
    "holidayHours",
    "holidayRanges",
)


def load_json(path: Path):
    return json.loads(path.read_text())


def save_json(path: Path, data) -> None:
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def apply_to_list(items: list, research: dict, checked_at: str) -> tuple[int, list]:
    missing = []
    updated = 0
    for v in items:
        slug = v["slug"]
        rec = research.get(slug)
        if not rec:
            missing.append(slug)
            # Mark call-ahead if no research entry
            v["hoursStatus"] = "call-ahead"
            v["hoursCheckedAt"] = checked_at
            v["hoursSource"] = None
            v["hoursNote"] = "Winter hours not verified — call ahead."
            v["hoursSchedules"] = []
            v["holidayClosures"] = []
            v["hours"] = ""
            updated += 1
            continue
        for key in HOURS_FIELDS:
            if key in rec:
                v[key] = rec[key]
            elif key in ("hoursSchedules", "holidayClosures"):
                v[key] = []
            elif key == "hoursCheckedAt":
                v[key] = checked_at
        if "hoursCheckedAt" not in rec:
            v["hoursCheckedAt"] = checked_at
        # Clear stale summer-only free-text when call-ahead with empty hours
        if v.get("hoursStatus") == "call-ahead" and not (rec.get("hours") or "").strip():
            v["hours"] = ""
        if v.get("hoursStatus") == "closed-season" and not (rec.get("hours") or "").strip():
            v["hours"] = "Closed for the season"
        updated += 1
    return updated, missing


def active_hours_for_display(venue: dict, month_day: str = "11-25") -> str:
    """Pick schedule hours for a representative late-November date."""
    status = venue.get("hoursStatus") or "verified"
    if status == "call-ahead":
        return (venue.get("hours") or "").strip()
    if status == "closed-season":
        schedules = venue.get("hoursSchedules") or []
        for s in schedules:
            if _in_range(month_day, s.get("validFrom"), s.get("validThrough")):
                return s.get("hours") or ""
        return venue.get("hours") or "Closed for the season"
    schedules = venue.get("hoursSchedules") or []
    matches = []
    for s in schedules:
        if _in_range(month_day, s.get("validFrom"), s.get("validThrough")):
            matches.append(s)
    if matches:
        matches.sort(key=lambda s: _span(s.get("validFrom"), s.get("validThrough")))
        return matches[0].get("hours") or venue.get("hours") or ""
    if schedules:
        return ""  # no covering schedule
    return venue.get("hours") or ""


def _in_range(md: str, fr: str | None, to: str | None) -> bool:
    fr = fr or "01-01"
    to = to or "12-31"
    if fr <= to:
        return fr <= md <= to
    return md >= fr or md <= to


def _span(fr: str | None, to: str | None) -> int:
    fr = fr or "01-01"
    to = to or "12-31"
    if fr <= to:
        a = int(fr[:2]) * 31 + int(fr[3:])
        b = int(to[:2]) * 31 + int(to[3:])
        return b - a
    return 200


def emit_venue_hours_js(all_venues: list) -> None:
    payload = {}
    for v in all_venues:
        slug = v["slug"]
        payload[slug] = {
            "slug": slug,
            "name": v.get("name"),
            "hours": v.get("hours") or "",
            "hoursStatus": v.get("hoursStatus") or "call-ahead",
            "hoursCheckedAt": v.get("hoursCheckedAt"),
            "hoursSource": v.get("hoursSource"),
            "hoursNote": v.get("hoursNote"),
            "hoursSchedules": v.get("hoursSchedules") or [],
            "holidayClosures": v.get("holidayClosures") or [],
            "holidayHours": v.get("holidayHours") or [],
            "holidayRanges": v.get("holidayRanges") or [],
        }
    # Alias
    if "forty-five-north" in payload:
        payload["45-north"] = payload["forty-five-north"]
    out = ROOT / "js/venue-hours-data.js"
    body = (
        "/** Auto-generated by scripts/apply_winter_hours.py — do not edit by hand. */\n"
        "(function (global) {\n"
        "  global.TCWT_VENUE_HOURS = "
        + json.dumps(payload, ensure_ascii=False, indent=2)
        + ";\n"
        "})(typeof window !== \"undefined\" ? window : globalThis);\n"
    )
    out.write_text(body)
    print(f"✓ {out.relative_to(ROOT)} ({len(payload)} keys)")


def patch_html_attrs() -> None:
    """Refresh data-hours / data-hours-status / data-hours-checked / data-hours-slug on cards."""
    wineries = load_json(ROOT / "data-wineries.json")["wineries"]
    cideries = load_json(ROOT / "data-cideries.json")
    breweries = load_json(ROOT / "data-breweries.json")
    by_slug = {v["slug"]: v for v in wineries + cideries + breweries}
    by_slug["45-north"] = by_slug.get("forty-five-north")

    def attrs_for(slug: str) -> str:
        v = by_slug.get(slug) or {}
        hours = active_hours_for_display(v)
        # Keep display hours field synced for HTML
        status = v.get("hoursStatus") or "call-ahead"
        checked = v.get("hoursCheckedAt") or ""
        parts = [
            f'data-hours="{_esc(hours)}"',
            f'data-hours-status="{_esc(status)}"',
            f'data-hours-checked="{_esc(checked)}"',
            f'data-hours-slug="{_esc(slug if slug != "45-north" else "forty-five-north")}"',
        ]
        return " ".join(parts)

    # Wineries index cards
    path = ROOT / "wineries/index.html"
    html = path.read_text()

    def card_repl(m: re.Match) -> str:
        tag = m.group(0)
        href = m.group(1)
        slug = href.rstrip("/").split("/")[-1]
        # strip existing hours attrs then re-add
        tag = re.sub(r'\s*data-hours(?:-status|-checked|-slug)?="[^"]*"', "", tag)
        tag = tag.replace(
            'class="winery-card"',
            f'class="winery-card" {attrs_for(slug)}',
            1,
        )
        return tag

    html = re.sub(
        r'<a href="(/wineries/[^"]+)" class="winery-card"[^>]*>',
        card_repl,
        html,
    )
    # Ensure venue-hours-data.js is loaded before hours.js
    html = _ensure_venue_hours_script(html)
    path.write_text(html)
    print("✓ wineries/index.html attrs")

    for rel, kind, items in [
        ("cideries/index.html", "cideries", cideries),
        ("breweries/index.html", "breweries", breweries),
    ]:
        path = ROOT / rel
        html = path.read_text()
        lines = html.splitlines(keepends=True)
        for i, line in enumerate(lines):
            if 'class="venue-card' in line:
                # find slug in following lines
                chunk = "".join(lines[i : min(i + 16, len(lines))])
                slug_m = re.search(rf'href="/{kind}/([^"]+)"', chunk)
                if not slug_m:
                    continue
                slug = slug_m.group(1)
                line2 = re.sub(
                    r'\s*data-hours(?:-status|-checked|-slug)?="[^"]*"',
                    "",
                    line,
                )
                line2 = re.sub(
                    r'(<div class="venue-card[^"]*")',
                    rf"\1 {attrs_for(slug)}",
                    line2,
                    count=1,
                )
                lines[i] = line2
        html = "".join(lines)
        html = _ensure_venue_hours_script(html)
        path.write_text(html)
        print(f"✓ {rel} attrs")

    # Individual winery pages
    for w in wineries:
        slug = w["slug"]
        pages = [ROOT / "wineries" / f"{slug}.html"]
        if slug == "forty-five-north":
            pages.append(ROOT / "wineries/45-north.html")
        hours = active_hours_for_display(w)
        status = w.get("hoursStatus") or "call-ahead"
        checked = w.get("hoursCheckedAt") or ""
        for page in pages:
            if not page.exists():
                continue
            html = page.read_text()
            html = re.sub(
                r'data-hours-block(?:\s+data-hours="[^"]*")?(?:\s+data-hours-status="[^"]*")?(?:\s+data-hours-checked="[^"]*")?(?:\s+data-hours-slug="[^"]*")?',
                f'data-hours-block data-hours="{_esc(hours)}" data-hours-status="{_esc(status)}" data-hours-checked="{_esc(checked)}" data-hours-slug="{_esc(slug)}"',
                html,
                count=1,
            )
            # Update openingHours string + specification
            html = _patch_schema(html, w, hours)
            html = _ensure_venue_hours_script(html)
            # Update hours-raw text if present
            html = re.sub(
                r'(<div class="hours-raw">)[^<]*(</div>)',
                rf"\1{_esc_html(hours or 'Call ahead — hours not verified for this season')}\2",
                html,
                count=1,
            )
            page.write_text(html)
        print(f"  ✓ wineries/{slug}.html")

    # winery-map inline hours
    path = ROOT / "winery-map.html"
    html = path.read_text()
    by_name = {w["name"].lower(): w for w in wineries}
    aliases = {
        "brys estate": "brys estate vineyard & winery",
        "45 north vineyard & winery": "forty-five north vineyard & winery",
        "bel lago vineyard": "bel lago vineyard & winery",
        "willow vineyards": "willow vineyard",
        "gill's pier winery": "gill's pier vineyard & winery",
    }

    def hours_repl(m: re.Match) -> str:
        obj = m.group(0)
        name_m = re.search(r'name:"([^"]+)"', obj)
        if not name_m:
            return obj
        key = name_m.group(1).lower()
        w = by_name.get(key)
        if not w:
            alias = aliases.get(key)
            if alias:
                w = by_name.get(alias)
        if not w:
            for kn, wv in by_name.items():
                if kn.startswith(key) or key.startswith(kn):
                    w = wv
                    break
        if not w:
            return obj
        hours = active_hours_for_display(w)
        status = w.get("hoursStatus") or "call-ahead"
        checked = w.get("hoursCheckedAt") or ""
        slug = w["slug"]
        obj = re.sub(r'hours:"[^"]*"', f'hours:"{hours}"', obj, count=1)
        if "hoursStatus:" not in obj:
            obj = obj[:-2] + f', hoursStatus:"{status}", hoursCheckedAt:"{checked}", slug:"{slug}" ' + obj[-2:]
        else:
            obj = re.sub(r'hoursStatus:"[^"]*"', f'hoursStatus:"{status}"', obj)
        return obj

    html = re.sub(
        r'\{ name:"[^"]+", type:"[^"]+", peninsula:"[^"]+",[\s\S]*?link:"[^"]+" \}',
        hours_repl,
        html,
    )
    html = _ensure_venue_hours_script(html)
    path.write_text(html)
    print("✓ winery-map.html")


def _esc(s: str) -> str:
    return (
        (s or "")
        .replace("&", "&amp;")
        .replace('"', "&quot;")
        .replace("<", "&lt;")
    )


def _esc_html(s: str) -> str:
    return (s or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _ensure_venue_hours_script(html: str) -> str:
    tag = '<script src="/js/venue-hours-data.js" defer></script>'
    if "/js/venue-hours-data.js" in html:
        return html
    if "/js/hours.js" in html:
        return html.replace(
            '<script src="/js/hours.js"',
            tag + '\n<script src="/js/hours.js"',
            1,
        )
    return html.replace("</body>", tag + "\n</body>", 1)


def _parse_hours_spec_simple(raw: str):
    """Minimal parser mirroring patch_open_this_week for schema rewrite."""
    from patch_open_this_week import parse_hours_spec

    return parse_hours_spec(raw)


def _patch_schema(html: str, venue: dict, hours: str) -> str:
    status = venue.get("hoursStatus") or "call-ahead"
    # Update openingHours string
    if '"openingHours"' in html:
        if hours:
            hours_json = json.dumps(hours)

            def _oh_repl(_m: re.Match) -> str:
                return f'"openingHours": {hours_json}'

            html = re.sub(
                r'"openingHours"\s*:\s*"[^"]*"',
                _oh_repl,
                html,
                count=1,
            )
        else:
            # remove openingHours and specification when unverified/empty
            html = re.sub(
                r',\s*"openingHours"\s*:\s*"[^"]*"',
                "",
                html,
                count=1,
            )

    # Remove existing specification; re-add only when verified + parseable
    html = re.sub(
        r',\s*"openingHoursSpecification"\s*:\s*\[[^\]]*\]',
        "",
        html,
        count=1,
    )

    if status != "verified" or not hours:
        return html

    specs = _parse_hours_spec_simple(hours)
    if not specs:
        return html

    # Attach seasonal validFrom/validThrough when a covering schedule exists
    md = "11-25"
    schedules = venue.get("hoursSchedules") or []
    covering = None
    for s in schedules:
        if _in_range(md, s.get("validFrom"), s.get("validThrough")):
            covering = s
            break
    if covering and covering.get("validFrom") and covering.get("validThrough"):
        y = 2026
        fr, to = covering["validFrom"], covering["validThrough"]
        if fr <= to:
            vf, vt = f"{y}-{fr}", f"{y}-{to}"
        else:
            vf, vt = f"{y}-{fr}", f"{y + 1}-{to}"
        for spec in specs:
            spec["validFrom"] = vf
            spec["validThrough"] = vt

    payload = json.dumps(specs, ensure_ascii=False)
    hours_json = json.dumps(hours)

    def _spec_after_oh(m: re.Match) -> str:
        return m.group(1) + ',\n      "openingHoursSpecification": ' + payload

    def _spec_after_tel(m: re.Match) -> str:
        return (
            m.group(1)
            + ',\n      "openingHours": '
            + hours_json
            + ',\n      "openingHoursSpecification": '
            + payload
        )

    if '"openingHours"' in html:
        html = re.sub(
            r'("openingHours"\s*:\s*"[^"]*")',
            _spec_after_oh,
            html,
            count=1,
        )
    else:
        html = re.sub(
            r'("telephone"\s*:\s*"[^"]*")',
            _spec_after_tel,
            html,
            count=1,
        )
    return html


def sync_display_hours(items: list) -> None:
    for v in items:
        disp = active_hours_for_display(v)
        if v.get("hoursStatus") == "closed-season" and not disp:
            v["hours"] = "Closed for the season"
        elif disp:
            v["hours"] = disp


def main() -> None:
    research_doc = load_json(RESEARCH)
    checked = research_doc.get("checkedAt") or "2026-11-25"
    wineries = load_json(ROOT / "data-wineries.json")
    cideries = load_json(ROOT / "data-cideries.json")
    breweries = load_json(ROOT / "data-breweries.json")

    n, miss = apply_to_list(
        wineries["wineries"], research_doc.get("wineries") or {}, checked
    )
    print(f"wineries updated: {n}; missing research: {miss}")
    n, miss = apply_to_list(cideries, research_doc.get("cideries") or {}, checked)
    print(f"cideries updated: {n}; missing research: {miss}")
    n, miss = apply_to_list(breweries, research_doc.get("breweries") or {}, checked)
    print(f"breweries updated: {n}; missing research: {miss}")

    sync_display_hours(wineries["wineries"])
    sync_display_hours(cideries)
    sync_display_hours(breweries)

    save_json(ROOT / "data-wineries.json", wineries)
    save_json(ROOT / "data-cideries.json", cideries)
    save_json(ROOT / "data-breweries.json", breweries)
    print("✓ data-*.json saved")

    emit_venue_hours_js(wineries["wineries"] + cideries + breweries)
    patch_html_attrs()
    print("done")


if __name__ == "__main__":
    main()
